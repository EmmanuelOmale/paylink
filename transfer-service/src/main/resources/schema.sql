CREATE TABLE IF NOT EXISTS wallets (
    id         VARCHAR(20)              PRIMARY KEY,
    currency   CHAR(3)                  NOT NULL,
    status     VARCHAR(10)              NOT NULL, -- ACTIVE | SUSPENDED | CLOSED
    balance    DECIMAL(19, 2)           NOT NULL CHECK (balance >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS transfers (
    rrn                   CHAR(12)                 PRIMARY KEY,
    source_wallet_id      VARCHAR(20)              NOT NULL,
    destination_wallet_id VARCHAR(20)              NOT NULL,
    amount                DECIMAL(19, 2)           NOT NULL CHECK (amount > 0),
    currency              CHAR(3)                  NOT NULL,
    remarks               VARCHAR(140),
    status                VARCHAR(15)              NOT NULL, -- INITIATED | RISK_APPROVED | COMPLETED | FAILED
    failure_reason        VARCHAR(30),                       -- INSUFFICIENT_FUNDS | RISK_DECLINED | RISK_UNAVAILABLE
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_transfers_source_created ON transfers (source_wallet_id, created_at);

CREATE TABLE IF NOT EXISTS ledger_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id    VARCHAR(20)              NOT NULL,
    transfer_rrn CHAR(12),
    entry_type   VARCHAR(6)               NOT NULL CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    amount       DECIMAL(19, 2)           NOT NULL CHECK (amount > 0),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (transfer_rrn, entry_type)
);

CREATE TABLE IF NOT EXISTS idempotency_keys (
    source_wallet_id VARCHAR(20)              NOT NULL,
    idempotency_key  VARCHAR(36)              NOT NULL,
    request_hash     CHAR(64)                 NOT NULL,
    status           VARCHAR(12)              NOT NULL, -- IN_PROGRESS | COMPLETED
    rrn              CHAR(12),
    http_status      INT,
    response_body    VARCHAR(4000),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (source_wallet_id, idempotency_key)
);

CREATE SEQUENCE IF NOT EXISTS rrn_seq START WITH 0 MINVALUE 0 MAXVALUE 999999 CYCLE;
